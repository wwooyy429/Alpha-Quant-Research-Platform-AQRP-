@pytest.mark.parametrize(
    "mutation,code",
    [
        ("quantity", "PUBLISHED_QUANTITY_CHANGED"),
        ("delta", "PUBLISHED_QUANTITY_CHANGED"),
        ("cash", "PUBLISHED_EQUITY_MISMATCH"),
        ("free_cash", "PUBLISHED_METRICS_CHANGED"),
        ("risk", "PUBLISHED_RISK_CHANGED"),
        ("context", "PUBLISHED_TARGET_CHANGED"),
        ("scope", "PUBLISHED_TARGET_CHANGED"),
        ("proposal", "PUBLISHED_DELTA_PROPOSAL_CHANGED"),
    ],
)
def test_actual_serialized_mutation_rejected(tmp_path, mutation, code):
    request = large_request()
    result = construct_engineering(request, tmp_path, OLD_SHA).read()
    if mutation == "quantity":
        result["target"]["quantities"]["SYNTH:A"] = str(10**35)
    if mutation == "delta":
        result["target"]["deltas"]["SYNTH:A"] = "0"
    if mutation == "cash":
        result["target"]["cash"] = "2"
    if mutation == "free_cash":
        result["target"]["free_cash"] = "2"
    if mutation == "risk":
        result["risk"]["passed"] = False
    if mutation == "context":
        result["target"]["context"]["snapshot_id"] = "wrong"
    if mutation == "scope":
        result["scope"] = "FORMAL"
    if mutation == "proposal":
        result["rebalance_proposals"][0]["delta_qty"] = "0"
    with pytest.raises(ContractError, match=code):
        audit_published(canonical(result), request, build_candidate(request))


def test_service_rejects_serializer_regression_before_publication(tmp_path, monkeypatch):
    import aqrp.portfolio.service as service

    def broken(value):
        data = load(canonical(value))
        if isinstance(data, dict) and "target" in data:
            data["target"]["quantities"]["SYNTH:A"] = str(10**35)
        return canonical(data)

    monkeypatch.setattr(service, "canonical", broken)
    result = service.construct_engineering(large_request(), tmp_path, OLD_SHA).read()
    assert result["status"] == "REJECTED"
    assert "target" not in result
    assert result["reasons"] == ["PUBLISHED_QUANTITY_CHANGED"]
    assert result["manifest"]["status"] == "FAILED"


def test_persisted_corruption_keeps_failure_and_cannot_replay_success(tmp_path, monkeypatch):
    original = ExperimentLedger.artifact

    def corrupted(self, run_id, name, value):
        if name == "result.json":
            value = load(canonical(value))
            value["target"]["cash"] = "2"
        return original(self, run_id, name, value)

    monkeypatch.setattr(ExperimentLedger, "artifact", corrupted)
    with pytest.raises(ContractError, match="PUBLISHED_EQUITY_MISMATCH"):
        construct_engineering(large_request(), tmp_path, OLD_SHA)
    run = next(tmp_path.iterdir()).name
    assert ExperimentLedger(tmp_path).verify(run)["status"] == "FAILED"
    assert load((tmp_path / run / "result.json").read_bytes())["target"]["cash"] == "2"
    assert (tmp_path / run / "publication-failure.json").is_file()
    with pytest.raises(ContractError, match="PUBLICATION_FAILED_NOT_REPLAYABLE"):
        replay_engineering(tmp_path, run)


