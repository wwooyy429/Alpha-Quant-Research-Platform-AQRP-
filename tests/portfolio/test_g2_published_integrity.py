@pytest.mark.parametrize("mutation", ["none", "manifest_id", "table_bytes"])
def test_real_nine_files_with_explicit_reference(tmp_path, mutation):
    x = load(bound().raw)
    source = x["source"]["research_bindings"][0]["snapshot"]
    destination = tmp_path / "dataset"
    shutil.copytree(source["root"], destination)
    folder = destination / source["snapshot_id"]
    assert len(list(folder.iterdir())) == 9
    if mutation == "manifest_id":
        p = folder / "manifest.json"
        data = json.loads(p.read_bytes())
        data["snapshot_id"] = "00000000-0000-4000-8000-000000000001"
        p.write_bytes(canonical(data))
    if mutation == "table_bytes":
        p = next(folder.glob("*.parquet"))
        p.write_bytes(p.read_bytes() + b"tamper")
    reference = SnapshotRef(destination, source["snapshot_id"], source["manifest_hash"])
    if mutation == "none":
        request = bind_research(
            projected_payload(), PUBLISHED / "runs", ORIGINAL, source_snapshot=reference
        )
        prepare(reseal(load(request.raw)))
    else:
        with pytest.raises(ContractError, match="RESEARCH_SNAPSHOT_VERIFICATION_FAILED"):
            bind_research(
                projected_payload(), PUBLISHED / "runs", ORIGINAL, source_snapshot=reference
            )


