@pytest.mark.parametrize(
    "exponent,price,lot,qty,cash",
    [
        (3, "1", "3", str(10**3 - 1), "1"),
        (34, "1", "3", str(10**34 - 1), "1"),
        (35, "1", "3", str(10**35 - 1), "1"),
        (40, "1", "3", str(10**40 - 1), "1"),
        (35, "0.01", "0.03", str(10**37 - 1) + ".99", "0.0001"),
        (100, "1e-100", "7", str(10**200 - 2), "0." + "0" * 99 + "2"),
        (-100, "1e100", "1e-100", "0", "0." + "0" * 99 + "1"),
    ],
)
def test_integer_derived_answers_and_persisted_byte_audit(
    tmp_path, exponent, price, lot, qty, cash
):
    # Independent formula: q = trunc(E / price / lot) * lot; cash = E - q*price.
    # Constants above are hand/integer derived, never generated by production functions.
    result = construct_engineering(
        large_request(exponent, price=price, lot=lot), tmp_path, OLD_SHA
    ).read()
    assert result["status"] == "SUCCEEDED", result.get("reasons")
    target = result["target"]
    assert target["quantities"]["SYNTH:A"] == qty
    assert target["cash"] == cash
    assert Q(qty) / Q(lot) == int(Q(qty) / Q(lot))
    assert Q(cash) + Q(qty) * Q(price) == Q("1e" + str(exponent))
    directory = tmp_path / result["run_id"]
    audit = load((directory / "published-byte-audit.json").read_bytes())
    assert (
        audit["result_sha256"]
        == hashlib.sha256((directory / "result.json").read_bytes()).hexdigest()
    )
    assert replay_engineering(tmp_path, result["run_id"])["result"]["target"] == target


def test_negative_targets_and_margin_do_not_lose_small_cash(tmp_path):
    result = construct_engineering(large_request(short=True), tmp_path, OLD_SHA).read()
    assert result["status"] == "SUCCEEDED", result.get("reasons")
    q = (10**35 - 4) // 2  # 5e34 % 3 == 2, both long and short truncate to a lot.
    assert set(result["target"]["quantities"].values()) == {str(q), str(-q)}
    assert Q(result["target"]["cash"]) == 10**35
    assert Q(result["target"]["restricted_cash"]) == q
    assert Q(result["target"]["margin_requirement"]) == q
    assert Q(result["target"]["free_cash"]) == 4


@pytest.mark.parametrize("value", [Q(0), Q(-3, 8), Q(7, 40), Q(10**200 - 2), Q(1, 10**100)])
def test_finite_output_exact_independent_of_decimal_context(value):
    with localcontext() as ctx:
        ctx.prec = 2
        assert Q(project(value)) == value


