OLD_SHA = "18439f31536295aea42e57e566d07cce345a35cf"


def large_request(exponent=35, *, price="1", lot="3", short=False):
    x = fixture()
    equity = "1e" + str(exponent)
    x["inputs"]["account"]["data"].update(equity=equity, total_cash=equity)
    x["policy"]["top_k"] = 1
    for row in x["inputs"]["prices"]["data"]:
        row.update(price=price, lot=lot)
    if short:
        x["policy"].update(mode="LONG_SHORT", gross="1", net="0")
        for row in x["inputs"]["permissions"]["data"]:
            row.update(short_permission=True, borrow_limit_total=equity)
    return reseal(x)


def test_g2_001_lossless_large_target_and_actual_returned_bytes(tmp_path):
    request = large_request()
    result = construct_engineering(request, tmp_path, OLD_SHA)
    data = load(result.raw)
    assert data["status"] == "SUCCEEDED"
    target = data["target"]
    # Hand integer answer: 10**35 % 3 == 1; rounding toward zero leaves cash 1.
    assert Q(target["quantities"]["SYNTH:A"]) == 10**35 - 1
    assert Q(target["deltas"]["SYNTH:A"]) == 10**35 - 1
    assert Q(target["cash"]) == 1
    assert Q(target["cash"]) + sum(Q(q) for q in target["quantities"].values()) == 10**35
    stored = load((tmp_path / data["run_id"] / "result.json").read_bytes())
    assert stored["target"] == target
    assert data["rebalance_proposals"][0]["delta_qty"] == target["deltas"]["SYNTH:A"]


